import assert from 'node:assert/strict';
import { createHash } from 'node:crypto';
import { createRequire } from 'node:module';
import { readFile, rename, writeFile } from 'node:fs/promises';
import { dirname, join, resolve } from 'node:path';
import { fileURLToPath } from 'node:url';
import { generateOfficeTemplate } from './lib/office-document-template-builders';
import { refreshOfficeTemplateDates } from '../packages/document-core/src/office-template-archive';
import type { GeneratedOfficeTemplates, OfficeTemplateKind } from '../packages/document-core/src/office-template-types';

// Explicit regeneration, not an application startup step:
//   npx tsx scripts/generate-office-document-templates.ts
// Commit the resulting TypeScript module together with any builder change.
const root = resolve(dirname(fileURLToPath(import.meta.url)), '..');
const require = createRequire(import.meta.url);
async function packageVersion(name: 'exceljs' | 'pptxgenjs') {
  let directory = dirname(require.resolve(name));
  for (;;) {
    try {
      const info = JSON.parse(await readFile(join(directory, 'package.json'), 'utf8')) as { name?: string; version?: string };
      if (info.name === name) { assert.match(info.version ?? '', /^\d+\.\d+\.\d+(?:[-+].*)?$/); return info.version!; }
    } catch (error) { if ((error as NodeJS.ErrnoException).code !== 'ENOENT') throw error; }
    const parent = dirname(directory); assert.notEqual(parent, directory, 'Cannot discover generator version: ' + name); directory = parent;
  }
}
const templates = {} as GeneratedOfficeTemplates['templates'];
// Canonical generation time makes re-running the script reproducible. Runtime
// creation always replaces these metadata and ZIP dates with the actual time.
const epoch = new Date('2000-01-01T00:00:00.000Z');
for (const kind of ['demo.pptx', 'empty.pptx', 'demo.xlsx', 'empty.xlsx'] as OfficeTemplateKind[]) {
  const format = kind.endsWith('.pptx') ? 'pptx' : 'xlsx';
  const bytes = await refreshOfficeTemplateDates(await generateOfficeTemplate(kind), format, epoch);
  templates[kind] = { format, sha256: createHash('sha256').update(bytes).digest('hex'), base64: Buffer.from(bytes).toString('base64') };
}
const data: GeneratedOfficeTemplates = { schemaVersion: 1, generators: { pptxgenjs: await packageVersion('pptxgenjs'), exceljs: await packageVersion('exceljs') }, templates };
const output = join(root, 'packages/document-core/src/generated-office-templates.ts');
const source = '// Generated by scripts/generate-office-document-templates.ts. Do not edit packages by hand.\n'
  + "import type { GeneratedOfficeTemplates } from './office-template-types';\n"
  + 'export const officeTemplates = ' + JSON.stringify(data, null, 2) + ' satisfies GeneratedOfficeTemplates;\n';
await writeFile(output + '.pending', source, 'utf8'); await rename(output + '.pending', output);
console.log(JSON.stringify({ output, generators: data.generators, templates: Object.fromEntries(Object.entries(templates).map(([kind, template]) => [kind, { bytes: Buffer.from(template.base64, 'base64').byteLength, sha256: template.sha256 }])) }));
